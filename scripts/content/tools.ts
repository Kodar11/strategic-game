// Content tooling. Run through npm:
//   npm run content:seed-sql   regenerate supabase/seed.sql from supabase/seed/content.json (checked first)
//   npm run content:validate   check the live published content against this app's engines (or --seed for the file)
//   npm run content:pull       write the live published content back into supabase/seed/content.json
// The live commands read EXPO_PUBLIC_SUPABASE_URL and EXPO_PUBLIC_SUPABASE_KEY from .env and use only the
// publishable key: they see exactly what the app sees.
import { readFileSync, writeFileSync } from 'node:fs';

import { createClient } from '@supabase/supabase-js';

import { buildCatalog } from '../../src/content/build.ts';
import type { Catalog } from '../../src/content/catalog.ts';
import { SEED_PATH, readSeed } from '../../src/content/seed.ts';

const SEED_SQL = 'supabase/seed.sql';

async function fetchLive(): Promise<unknown> {
  const url = process.env.EXPO_PUBLIC_SUPABASE_URL;
  const key = process.env.EXPO_PUBLIC_SUPABASE_KEY;
  if (!url || !key) throw new Error('Set EXPO_PUBLIC_SUPABASE_URL and EXPO_PUBLIC_SUPABASE_KEY in .env');
  const client = createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
  const { data, error } = await client.rpc('get_published_content');
  if (error) throw new Error(`get_published_content failed: ${error.code} ${error.message}`);
  return data;
}

/**
 * Every engine-backed claim, checked as the test suite checks it: a calculable scenario's solver picks the one option
 * marked `match`; an uncertain one marks none; an assessment solver picks the item's matching option.
 */
function solverProblems(c: Catalog): string[] {
  const out: string[] = [];
  for (const s of c.scenarios) {
    const matches = s.predict.options.filter((o) => o.verdict === 'match');
    if (s.predict.basis === 'uncertain') {
      if (matches.length) out.push(`scenario ${s.id} is uncertain but marks an option as a match`);
    } else if (!s.predict.solve) out.push(`scenario ${s.id} is calculable but its engine has no solver`);
    else if (matches.length !== 1 || s.predict.solve() !== matches[0].id) out.push(`scenario ${s.id}: the engine solves to "${s.predict.solve()}", but the content marks ${matches.map((m) => `"${m.id}"`).join(', ') || 'nothing'} as the match`);
  }
  for (const a of c.assessments) {
    for (const i of a.items) {
      if (i.solve && i.solve() !== i.options.find((o) => o.verdict === 'match')?.id) out.push(`assessment item ${a.id}/${i.id}: the engine solves to "${i.solve()}", which is not the option marked as the match`);
    }
  }
  return out;
}

function check(doc: unknown, where: string): Catalog {
  const r = buildCatalog(doc);
  const problems = r.ok ? solverProblems(r.catalog) : r.problems;
  if (problems.length) {
    console.error(`${where}: ${problems.length} problem(s)\n${problems.map((p) => `  - ${p}`).join('\n')}`);
    process.exit(1);
  }
  return (r as { catalog: Catalog }).catalog;
}

function summary(c: Catalog): string {
  return `${c.modules.length} modules, ${c.lessons.length} lessons, ${c.scenarios.length} scenarios, ${c.challenges.length} challenges, ${c.assessments.length} assessments`;
}

const [command, flag] = process.argv.slice(2);

if (command === 'seed-sql') {
  const raw = readFileSync(SEED_PATH, 'utf8');
  const c = check(JSON.parse(raw), 'supabase/seed/content.json');
  const tag = '$content$';
  if (raw.includes(tag)) throw new Error(`the seed contains ${tag}; pick another dollar-quote tag`);
  const doc = JSON.stringify(JSON.parse(raw));
  writeFileSync(
    SEED_SQL,
    `-- Generated by \`npm run content:seed-sql\` from supabase/seed/content.json. Do not edit by hand.
-- Imports the content catalog (${summary(c)}).
-- Safe to re-run: rows are inserted when missing and updated only when the seed's revision is higher.
-- Run after the migrations, as the database owner (SQL editor, psql or \`supabase db reset\`).

select entity, action, count(*) as rows
from content_admin.import_content(${tag}${doc}${tag}::jsonb)
group by entity, action
order by entity, action;

-- Expect no rows: every structural rule holds.
select * from content_admin.validate_content();

-- Assign lesson categories to lessons that have none yet (never moves an existing assignment).
select content_admin.seed_lesson_categories() as lesson_categories_assigned;
`,
  );
  console.log(`wrote ${SEED_SQL} (${summary(c)})`);
} else if (command === 'validate') {
  const fromSeed = flag === '--seed';
  const doc = fromSeed ? readSeed() : await fetchLive();
  const c = check(doc, fromSeed ? 'supabase/seed/content.json' : 'published content');
  console.log(`${fromSeed ? 'seed' : 'published content'} is valid: ${summary(c)}`);
  if (!fromSeed) {
    const same = JSON.stringify(doc) === JSON.stringify(readSeed());
    console.log(same ? 'it matches supabase/seed/content.json exactly' : 'it differs from supabase/seed/content.json (run `npm run content:pull` to record the database version)');
  }
} else if (command === 'pull') {
  const doc = await fetchLive();
  const c = check(doc, 'published content');
  writeFileSync(SEED_PATH, `${JSON.stringify(doc, null, 2)}\n`);
  console.log(`wrote supabase/seed/content.json from the database (${summary(c)}). Review the diff, then run npm run content:seed-sql.`);
} else {
  console.error('usage: tools.ts seed-sql | validate [--seed] | pull');
  process.exit(2);
}
