// Writes supabase/tournament/season1.sql from the bundled Season 1 (src/tournament/season1.ts), so the server copy
// and the app's copy are the same document. Run after editing season1.ts:
//
//   node scripts/tournament-seed.mjs
//
// supabase/__tests__/tournament.test.ts fails when the two differ.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { SEASON_ONE } from '../src/tournament/season1.ts';

export function seasonOneSql(doc = SEASON_ONE) {
  const json = JSON.stringify(doc, null, 2);
  if (json.includes('$doc$')) throw new Error('the document contains the SQL quote marker $doc$');
  return [
    '-- Generated by scripts/tournament-seed.mjs from src/tournament/season1.ts. Do not edit by hand: edit season1.ts and',
    '-- run the script, or change the stored document with the statements in manage.sql.',
    '--',
    '-- Run once in the SQL editor to publish Season 1. Re-running replaces the stored document and bumps its revision.',
    'insert into public.tournament_documents (id, status, document)',
    `values ('main', 'published', $doc$${json}$doc$::jsonb)`,
    'on conflict (id) do update set document = excluded.document, status = excluded.status, revision = public.tournament_documents.revision + 1;',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase', 'tournament', 'season1.sql');
  writeFileSync(out, seasonOneSql());
  console.log(`wrote ${out}`);
}
