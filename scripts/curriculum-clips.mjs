#!/usr/bin/env node
// Snapshot the curriculum lessons' spoken lines from the content seed into src/features/audio/curriculum-clips.ts.
// Run after the curriculum content changes (and `npm run content:pull`), then `npm run tts` for any new or stale
// clips. No API calls.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/features/audio/curriculum-clips.ts');
const load = (rel) => import(pathToFileURL(path.join(ROOT, rel)).href);

const { installSeedCatalog } = await load('src/content/seed.ts');
const { LESSON_IDS } = await load('src/content/lessons.ts');
const { curriculumLines } = await load('src/features/audio/curriculum-lines.ts');

const catalog = installSeedCatalog();
const ids = LESSON_IDS.filter((id) => catalog.curriculum.has(id));
const clips = ids.flatMap((id) => curriculumLines(id, catalog.curriculum.get(id)));

const field = (k, v) => `${k}: ${JSON.stringify(v)}`;
const body = ids
  .map((lesson) => {
    const rows = clips
      .filter((c) => c.lesson === lesson)
      .map((c) => `  { ${['id', 'lesson', 'character', 'style', 'sync', 'text'].map((k) => field(k, c[k])).join(', ')} },`);
    return [`  // ── ${lesson} ──`, ...rows].join('\n');
  })
  .join('\n\n');

await fs.writeFile(
  OUT,
  `// Generated by scripts/curriculum-clips.mjs from supabase/seed/content.json. Do not edit by hand.
import type { ClipDef } from './clips.ts';

/** Spoken lines of the curriculum lessons, as the content seed has them. See curriculum-lines.ts. */
export const CURRICULUM_CLIPS = [
${body}
] as const satisfies readonly ClipDef[];
`,
);
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${clips.length} clips across ${ids.length} lessons.`);
