#!/usr/bin/env node
// Writes src/features/audio/story-clips.ts: every spoken line in both stories. Story One's lines are found by walking
// every branch of the script; Story Two's are listed in src/stories/meridian/narration.ts. Run: npm run stories:clips
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const load = (p) => import(pathToFileURL(path.join(ROOT, p)).href);
const { allSpokenLines } = await load('src/stories/crossing/narration.ts');
const { MERIDIAN_LINES, CROSSING_REFLECTION_LINES } = await load('src/stories/meridian/narration.ts');

const rows = [
  ...allSpokenLines().map((l) => ({ id: l.id, lesson: 'dbu', character: l.voice, style: l.style, sync: 'spoken', text: l.text })),
  ...Object.entries(CROSSING_REFLECTION_LINES).map(([id, text]) => ({ id, lesson: 'dbu', character: 'storyteller', style: 'narration', sync: 'computed', text })),
  ...Object.entries(MERIDIAN_LINES).map(([id, text]) => ({ id, lesson: 'mer', character: 'steward', style: 'narration', sync: 'computed', text })),
];
const body = rows.map((r) => `  ${JSON.stringify(r)},`).join('\n');
await fs.writeFile(
  path.join(ROOT, 'src/features/audio/story-clips.ts'),
  `// AUTO-GENERATED by scripts/story-audio/story-clips.mjs — do not edit by hand. Regenerate with: npm run stories:clips\n\nexport const STORY_CLIPS = [\n${body}\n] as const;\n`,
);
console.log(`Wrote story-clips.ts with ${rows.length} clips.`);
