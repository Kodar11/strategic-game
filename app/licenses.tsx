import { router } from 'expo-router';
import { useMemo, useState } from 'react';
import { FlatList, Pressable, StyleSheet, TextInput, View } from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';

import { AppText } from '@/src/components/ui/AppText';
import { Backdrop } from '@/src/components/ui/Backdrop';
import { IconButton } from '@/src/components/ui/Button';
import { ArrowLeft, ChevronDown, Search } from '@/src/components/ui/icons';
import { MAX_CONTENT_WIDTH, MAX_FONT_SCALE, colors, fonts, radius, space } from '@/src/theme/tokens';

interface LicenseEntry {
  name: string;
  version: string;
  license: string;
  /** Index into `texts`, or null when the package ships no licence file. */
  text: number | null;
}
interface LicenseData {
  packages: LicenseEntry[];
  texts: string[];
}

/**
 * Open-source licences of the app's production dependencies, generated by scripts/generate-licenses.mjs
 * (`npm run licenses`). A searchable list of name, version and licence; a package's full licence text opens on tap.
 * The data (~0.5 MB) is loaded only when this screen opens.
 */
export default function LicensesScreen() {
  const insets = useSafeAreaInsets();
  // Loaded on demand (require, not import), so the ~0.5 MB list isn't evaluated at app start.
  const data = useMemo(() => require('@/src/features/settings/licenses.json') as LicenseData, []);
  const [query, setQuery] = useState('');
  const [open, setOpen] = useState<string | null>(null);
  const back = () => (router.canGoBack() ? router.back() : router.replace('/about'));

  const shown = useMemo(() => {
    const q = query.trim().toLowerCase();
    return q ? data.packages.filter((p) => p.name.toLowerCase().includes(q) || p.license.toLowerCase().includes(q)) : data.packages;
  }, [data, query]);

  return (
    <View style={{ flex: 1, backgroundColor: colors.bg }}>
      <Backdrop />
      <FlatList
        data={shown}
        keyExtractor={(p) => `${p.name}@${p.version}`}
        initialNumToRender={25}
        keyboardShouldPersistTaps="handled"
        contentContainerStyle={{ padding: space.lg, paddingTop: insets.top + space.md, paddingBottom: insets.bottom + space.xxl }}
        ListHeaderComponent={
          <View style={[styles.column, { gap: space.md, paddingBottom: space.md }]}>
            <View style={styles.head}>
              <IconButton icon={ArrowLeft} label="Back" onPress={back} />
              <AppText variant="title" accessibilityRole="header" style={{ flex: 1 }}>
                Open-source licences
              </AppText>
            </View>
            <AppText variant="small" color={colors.textMuted}>
              Tactiqo is built with {data.packages.length} open-source packages. Tap one to read its licence.
            </AppText>
            <View style={styles.search}>
              <Search size={18} color={colors.textMuted} />
              <TextInput
                maxFontSizeMultiplier={MAX_FONT_SCALE}
                value={query}
                onChangeText={setQuery}
                placeholder="Search packages or licences"
                placeholderTextColor={colors.textFaint}
                autoCapitalize="none"
                autoCorrect={false}
                accessibilityLabel="Search packages or licences"
                style={styles.searchInput}
              />
            </View>
          </View>
        }
        ListEmptyComponent={
          <AppText variant="small" color={colors.textMuted} style={styles.column}>
            No package matches “{query.trim()}”.
          </AppText>
        }
        renderItem={({ item }) => {
          const key = `${item.name}@${item.version}`;
          const expanded = open === key;
          const text = item.text === null ? null : data.texts[item.text];
          return (
            <View style={[styles.column, styles.item]}>
              <Pressable
                onPress={() => setOpen(expanded ? null : key)}
                accessibilityRole="button"
                accessibilityState={{ expanded }}
                accessibilityLabel={`${item.name}, version ${item.version}, ${item.license} licence`}
                style={({ pressed }) => [styles.row, pressed && { backgroundColor: colors.surfaceHigh }]}>
                <View style={{ flex: 1, gap: 2 }}>
                  <AppText variant="bodyStrong" numberOfLines={2}>
                    {item.name}
                  </AppText>
                  <AppText variant="caption" color={colors.textMuted}>
                    {item.version} · {item.license}
                  </AppText>
                </View>
                <ChevronDown size={18} color={colors.textMuted} style={expanded ? { transform: [{ rotate: '180deg' }] } : undefined} />
              </Pressable>
              {expanded ? (
                <AppText variant="caption" color={colors.textBody} selectable style={styles.text}>
                  {text ?? `This package doesn’t include a licence file. Its package information declares: ${item.license}.`}
                </AppText>
              ) : null}
            </View>
          );
        }}
      />
    </View>
  );
}

const styles = StyleSheet.create({
  column: { maxWidth: MAX_CONTENT_WIDTH, width: '100%', alignSelf: 'center' },
  head: { flexDirection: 'row', alignItems: 'center', gap: space.sm },
  search: {
    flexDirection: 'row',
    alignItems: 'center',
    gap: space.sm,
    minHeight: 48,
    paddingHorizontal: space.md,
    borderRadius: radius.lg,
    borderWidth: 1,
    borderColor: colors.borderStrong,
    backgroundColor: colors.surface,
  },
  searchInput: { flex: 1, minHeight: 44, color: colors.text, fontFamily: fonts.medium, fontSize: 16 },
  item: { borderBottomWidth: StyleSheet.hairlineWidth, borderBottomColor: colors.border },
  row: { flexDirection: 'row', alignItems: 'center', gap: space.md, minHeight: 56, paddingVertical: space.sm, paddingHorizontal: space.xs, borderRadius: radius.md },
  text: { paddingHorizontal: space.xs, paddingBottom: space.md, fontFamily: fonts.regular },
});
